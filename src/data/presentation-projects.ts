import photoInventory from "@/data/presentation-photos.json";
import type { Project, ProjectPhoto } from "@/data/projects";

type PresentationSlug = keyof typeof photoInventory;
type PresentationProject = Omit<Project, "slug" | "source" | "image" | "imageAlt" | "hero" | "photos">;

function presentationProject(
  slug: PresentationSlug,
  facts: PresentationProject,
  cardPhoto: string,
  heroPhoto = cardPhoto,
): Project {
  // Every image key in the slide inventory has a corresponding optimized media entry.
  const photos = photoInventory[slug] as ProjectPhoto[];
  const card = photos.find(({ image }) => image.endsWith("/" + cardPhoto));
  const hero = photos.find(({ image }) => image.endsWith("/" + heroPhoto));
  if (!card || !hero) throw new Error("Missing presentation photo for " + slug);
  return { ...facts, slug, image: card.image, imageAlt: card.caption, hero, photos, source: "presentation" };
}

